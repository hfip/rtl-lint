"""Turn a scan into a migration plan, report and optional branch."""

from __future__ import annotations

import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from . import __version__
from .rules import RULES, SWIFT
from .scanner import Config, Issue, discover, run

STRING_CALL_RE = re.compile(
    r"\b(?:Text|Label|Button|TextField|SecureField|Toggle|Section)\s*\(\s*"
    r'"((?:[^"\\]|\\.)*)"'
)
FIX_GROUPS: Tuple[str, ...] = ("RTL001", "RTL002", "RTL003")
DECISION_CODES = ("RTL004", "RTL005", "RTL006", "RTL007", "RTL008", "RTL009")

RULE_LABELS = {
    "RTL001": "alignment",
    "RTL002": "explicit enums",
    "RTL003": "anchors and attributes",
    "RTL004": "physical edge insets",
    "RTL005": "forced direction",
    "RTL006": "manual direction branches",
    "RTL007": "manual mirroring",
    "RTL008": "storyboard alignment",
    "RTL009": "storyboard forced direction",
}


class MigrationError(Exception):
    pass


@dataclass
class HardcodedString:
    path: Path
    line: int
    text: str


@dataclass
class MigrationPlan:
    files_scanned: int
    issues: List[Issue] = field(default_factory=list)
    strings: List[HardcodedString] = field(default_factory=list)

    @property
    def mechanical(self) -> List[Issue]:
        return [issue for issue in self.issues if issue.replacement is not None]

    @property
    def decisions(self) -> List[Issue]:
        return [issue for issue in self.issues if issue.replacement is None]

    def by_code(self, codes: Sequence[str]) -> Dict[str, List[Issue]]:
        grouped: Dict[str, List[Issue]] = {code: [] for code in codes}
        for issue in self.issues:
            if issue.code in grouped:
                grouped[issue.code].append(issue)
        return grouped


def find_hardcoded_strings(paths: Sequence[str], config: Config) -> List[HardcodedString]:
    found: List[HardcodedString] = []
    for path, kind in discover(paths, config.exclude):
        if kind != SWIFT:
            continue
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for number, line in enumerate(text.split("\n"), start=1):
            if line.lstrip().startswith("//"):
                continue
            for match in STRING_CALL_RE.finditer(line):
                value = match.group(1)
                if not any(char.isalpha() for char in value):
                    continue
                found.append(HardcodedString(path=path, line=number, text=value))
    return found


def build_markdown(plan: MigrationPlan, root: Optional[Path] = None) -> str:
    def display(path: Path) -> str:
        if root is None:
            return str(path)
        try:
            return str(path.resolve().relative_to(root.resolve()))
        except ValueError:
            return str(path)

    lines: List[str] = []
    lines.append("# RTL migration plan")
    lines.append("")
    lines.append(
        "Generated by rtl-lint %s from %d Swift/storyboard files."
        % (__version__, plan.files_scanned)
    )
    lines.append("")

    mechanical = plan.mechanical
    decisions = plan.decisions
    lines.append("## 1. Mechanical fixes (%d)" % len(mechanical))
    lines.append("")
    if mechanical:
        lines.append("Safe rewrites: `left` becomes `leading`, `right` becomes `trailing`.")
        lines.append("")
        lines.append("| rule | what | count | files |")
        lines.append("| --- | --- | --- | --- |")
        for code in FIX_GROUPS:
            group = [issue for issue in mechanical if issue.code == code]
            if not group:
                continue
            rule = next(rule for rule in RULES if rule.code == code)
            files = len({issue.path for issue in group})
            lines.append("| %s | %s | %d | %d |" % (code, RULE_LABELS[code], len(group), files))
    else:
        lines.append("Nothing to rewrite automatically.")
    lines.append("")

    lines.append("## 2. Needs a decision (%d)" % len(decisions))
    lines.append("")
    if decisions:
        for code in DECISION_CODES:
            group = [issue for issue in decisions if issue.code == code]
            if not group:
                continue
            rule = next(rule for rule in RULES if rule.code == code)
            lines.append("### %s: %s (%d)" % (code, RULE_LABELS[code], len(group)))
            lines.append("")
            lines.append("%s" % rule.hint)
            lines.append("")
            for issue in group[:20]:
                lines.append("- `%s:%d`" % (display(issue.path), issue.line))
            if len(group) > 20:
                lines.append("- … and %d more" % (len(group) - 20))
            lines.append("")
    else:
        lines.append("Nothing here. That is unusual; check the storyboards by hand.")
        lines.append("")

    lines.append("## 3. Not checked")
    lines.append("")
    lines.append("- Images that should mirror (timeline icons, directional arrows).")
    lines.append("- Numbers, dates and currency formatting.")
    lines.append("- Truncation in Arabic, which is usually longer than English.")
    lines.append("")
    if plan.strings:
        per_file: Dict[Path, int] = {}
        for item in plan.strings:
            per_file[item.path] = per_file.get(item.path, 0) + 1
        lines.append("### User-facing literals (%d)" % len(plan.strings))
        lines.append("")
        lines.append("These are string literals passed to `Text`, `Button` and friends. They are")
        lines.append("localizable keys; verify each one exists in the String Catalog.")
        lines.append("")
        lines.append("| file | literals |")
        lines.append("| --- | --- |")
        for path, count in sorted(per_file.items(), key=lambda item: -item[1])[:15]:
            lines.append("| %s | %d |" % (display(path), count))
        lines.append("")

    lines.append("## Checklist")
    lines.append("")
    lines.append("- [ ] Apply the mechanical fixes on a branch and review the diff.")
    lines.append("- [ ] Go through section 2 one rule at a time.")
    lines.append("- [ ] Check that every image with a direction still makes sense in Arabic.")
    lines.append("- [ ] Run the app in an Arabic locale and screenshot the main screens.")
    lines.append("- [ ] Add `ar` to the catalog and check plural forms.")
    lines.append("")
    return "\n".join(lines)


def _git(root: Path, *args: str, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", str(root), *args],
        capture_output=True,
        text=True,
        check=check,
    )


def repository_root(paths: Sequence[str]) -> Optional[Path]:
    start = Path(paths[0]).expanduser() if paths else Path.cwd()
    if start.is_file():
        start = start.parent
    result = _git(start, "rev-parse", "--show-toplevel", check=False)
    if result.returncode != 0:
        return None
    return Path(result.stdout.strip())


def apply_plan(
    paths: Sequence[str],
    config: Config,
    root: Path,
    branch: Optional[str],
    report: Optional[Path],
    report_text: str,
    force: bool = False,
) -> Tuple[List[str], List[str]]:
    if not force:
        status = _git(root, "status", "--porcelain")
        if status.stdout.strip():
            raise MigrationError("working tree is not clean; commit, stash, or pass --force")

    if branch:
        existing = _git(root, "rev-parse", "--verify", branch, check=False)
        if existing.returncode == 0:
            raise MigrationError("branch %r already exists" % branch)
        _git(root, "checkout", "-b", branch)

    commits: List[str] = []
    for code in FIX_GROUPS:
        ignored = tuple(rule.code for rule in RULES if rule.code != code)
        group_config = Config(
            exclude=config.exclude,
            ignore=ignored,
            severity=dict(config.severity),
        )
        result = run(paths, group_config, fix=True)
        if result.fixed == 0:
            continue
        _git(root, "add", "-A")
        _git(
            root,
            "commit",
            "-m",
            "rtl: %s %s (%d fixes)" % (code, _rule_message(code), result.fixed),
        )
        plural = "fix" if result.fixed == 1 else "fixes"
        commits.append("%s %s (%d %s)" % (code, _rule_message(code), result.fixed, plural))

    if report is not None:
        report.write_text(report_text, encoding="utf-8")
        _git(root, "add", str(report))
        _git(root, "commit", "-m", "docs: RTL migration plan")
        commits.append(report.name)

    return commits, []


def _rule_message(code: str) -> str:
    for rule in RULES:
        if rule.code == code:
            return {
                "RTL001": "alignment",
                "RTL002": "explicit alignment enums",
                "RTL003": "layout anchors",
            }.get(code, rule.message)
    return code


def migration_json(plan: MigrationPlan, root: Optional[Path]) -> dict:
    def display(path: Path) -> str:
        if root is None:
            return str(path)
        try:
            return str(path.resolve().relative_to(root.resolve()))
        except ValueError:
            return str(path)

    return {
        "version": __version__,
        "files": plan.files_scanned,
        "mechanical": len(plan.mechanical),
        "decisions": len(plan.decisions),
        "strings": len(plan.strings),
        "rules": sorted({issue.code for issue in plan.issues}),
        "details": [
            {
                "code": issue.code,
                "path": display(issue.path),
                "line": issue.line,
                "fixable": issue.fixable,
            }
            for issue in plan.issues
        ],
    }
